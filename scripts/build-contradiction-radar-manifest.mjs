#!/usr/bin/env node
// Contradiction Radar's real data source: this repo's own docs/outbox/
// corpus (89 real session docs at the time this was written) -- every
// place the project caught and documented its own wrong assumption. A
// resolved contradiction (old claim vs. corrected claim, both real,
// both in this repo's own history) is a genuine "contradiction," found
// by scanning for a real, observed vocabulary already confirmed present
// via direct grep against the corpus (`turned out`, `was wrong`,
// `originally (built|assumed|thought)`, `corrected`, `did not match`,
// `misclassified`, `false negative`, `false positive`, `regressed`) --
// exact substring matching against a fixed, closed list, not fuzzy NLP.
//
// Runs at build time, NOT in the browser: bundling all 628KB of raw
// markdown into the client would roughly double the app's JS payload
// for a handful of real findings. This generates a small precomputed
// JSON manifest (just the matched sentences + doc metadata) that the
// component imports directly -- committed to the repo like any other
// generated asset, regenerated by re-running this script when new
// outbox docs are added.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const REPO_ROOT = new URL('..', import.meta.url).pathname
const OUTBOX_DIR = join(REPO_ROOT, 'docs/outbox')
const OUT_PATH = join(REPO_ROOT, 'src/data/contradictionRadarManifest.json')

// Fixed, closed vocabulary -- confirmed present in this real corpus via
// direct grep before this list was written, not guessed.
const PHRASES = [
  'turned out to be', 'turned out not', 'was wrong', 'originally built',
  'originally assumed', 'originally thought', 'corrected', 'did not match',
  "didn't match", 'misclassified', 'false negative', 'false positive', 'regressed',
]

function splitSentences(text) {
  // Naive but real: split into paragraphs on blank lines first (this
  // repo's own outbox docs consistently separate headers/metadata
  // blocks from prose with a blank line -- confirmed by inspecting the
  // actual raw files, not assumed), skip paragraphs that are pure
  // markdown structure (headers, `---`, tables), then split surviving
  // prose paragraphs on sentence-ending punctuation. Good enough for
  // this repo's own consistent doc style; not a general-purpose parser.
  const paragraphs = text.split(/\n\s*\n/)
  const sentences = []
  for (const para of paragraphs) {
    const flat = para.replace(/\n+/g, ' ').trim()
    if (!flat || /^#|^---+$|^\|/.test(flat)) continue
    for (const s of flat.split(/(?<=[.!?])\s+/)) {
      if (s.trim()) sentences.push(s.trim())
    }
  }
  return sentences
}

function titleOf(text) {
  const m = text.match(/^#\s+(.+)$/m)
  return m ? m[1].trim() : null
}

function dateOf(filename) {
  const m = filename.match(/(\d{4}-\d{2}-\d{2})/)
  return m ? m[1] : null
}

function main() {
  const files = readdirSync(OUTBOX_DIR).filter(f => f.endsWith('.md')).sort()
  const findings = []

  for (const filename of files) {
    const full = join(OUTBOX_DIR, filename)
    const text = readFileSync(full, 'utf-8')
    const title = titleOf(text) ?? filename
    const date = dateOf(filename)
    const sentences = splitSentences(text)

    for (const sentence of sentences) {
      const lower = sentence.toLowerCase()
      const matched = PHRASES.find(p => lower.includes(p))
      if (matched) {
        const trimmed = sentence.trim().replace(/\s+/g, ' ')
        if (trimmed.length > 4 && trimmed.length < 400) {
          findings.push({ file: filename, title, date, phrase: matched, sentence: trimmed })
        }
      }
    }
  }

  const manifest = {
    generatedFrom: files.length + ' real docs in docs/outbox/',
    phrases: PHRASES,
    findingCount: findings.length,
    findings,
  }
  writeFileSync(OUT_PATH, JSON.stringify(manifest, null, 2) + '\n')
  console.log('Wrote ' + OUT_PATH + ': ' + findings.length + ' findings across ' + files.length + ' docs.')
}

main()
