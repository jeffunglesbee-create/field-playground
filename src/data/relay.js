// --- Ambient week: real multi-day sample for AmbientPanel's top section ---
// AmbientPanel's content (star rating, editorial claim, sport of the
// week, quality alerts) is entirely server-generated by the ONE real
// per-date endpoint above -- there's no server-side range/limit param
// to request a bigger sample the way DramaLeaderboard/HallOfSurprises
// have. Confirmed real and safe to build on via a direct multi-date
// probe, 2026-08-03 (outbox/ambient-multiday-probe-2026-08-03T18-06-10-
// 315Z.txt): 10/10 real recent dates resolved, 10/10 distinct real
// editorial claims. This calls the SAME real per-date endpoint across a
// real N-day window and returns each day's raw result tagged
// fulfilled/failed -- not collapsed into a misleading empty state on a
// partial outage, matching the fix already applied to
// VenueGeocodeRace/weather.js's own Promise.allSettled consumers.
const AMBIENT_WEEK_DAYS = 10

function shiftDateStr(dateStr, deltaDays) {
  const d = new Date(`${dateStr}T00:00:00Z`)
  d.setUTCDate(d.getUTCDate() + deltaDays)
  return d.toISOString().split('T')[0]
}

async function fetchAmbientWeek(endDate) {
  const dates = []
  for (let i = 0; i < AMBIENT_WEEK_DAYS; i++) dates.push(shiftDateStr(endDate, -i))
  const settled = await Promise.allSettled(dates.map(fetchAmbient))
  return dates.map((date, i) => {
    const r = settled[i]
    return r.status === 'fulfilled'
      ? { date, ok: true, data: r.value }
      : { date, ok: false, error: String(r.reason) }
  })
}

export const [ambientWeek, { refetch: refetchAmbientWeek }] = createResource(currentDate, fetchAmbientWeek)

